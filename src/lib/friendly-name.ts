function randomItem<T>(items: readonly T[]): T {
    return items[crypto.getRandomValues(new Uint32Array(1))[0] % items.length];
}

export function generateFriendlyName(): string {
    return `${randomItem(modifiers)}-${randomItem(subjects)}`;
}
